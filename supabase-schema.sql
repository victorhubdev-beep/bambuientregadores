create table if not exists public.deliveries (
  id bigint generated by default as identity primary key,
  client text not null,
  address text not null,
  store text not null default 'Loja não definida',
  rider text not null default 'Atribuir depois',
  status text not null default 'Pendente' check (status in ('Pendente', 'Em andamento', 'Concluída')),
  created_by uuid not null references auth.users(id) default auth.uid(),
  created_at timestamptz not null default now()
);

alter table public.deliveries enable row level security;
create policy "authenticated users read deliveries" on public.deliveries
  for select to authenticated using (true);
create policy "authenticated users insert own deliveries" on public.deliveries
  for insert to authenticated with check (auth.uid() = created_by);
create policy "authenticated users update deliveries" on public.deliveries
  for update to authenticated using (true) with check (true);
